CREATE TABLE IF NOT EXISTS razorpay_test_payout (
 request_id CHAR(36) PRIMARY KEY,
 customer_id INT NOT NULL,
 from_acc_no BIGINT UNSIGNED NOT NULL,
 amount_paise INT UNSIGNED NOT NULL,
 recipient_vpa VARCHAR(193) NOT NULL,
 recipient_name VARCHAR(100) NOT NULL,
 provider_id VARCHAR(64) NULL UNIQUE,
 state ENUM('RESERVED','PROCESSED','RELEASED') NOT NULL DEFAULT 'RESERVED',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (customer_id) REFERENCES customer(cust_id),
 FOREIGN KEY (from_acc_no) REFERENCES account(acc_no)
) ENGINE=InnoDB;
